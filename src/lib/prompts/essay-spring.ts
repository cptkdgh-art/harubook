import type { EssayPromptInput } from './essay-base';
import { buildBasePrompt } from './essay-base';

/* ════════════════════════════════
   봄날 확장 프롬프트
   ════════════════════════════════ */

export function buildSpringPrompt(input: EssayPromptInput): string {
  const base = buildBasePrompt(input);

  const springExtension = `

━━━━━━━━━━━━━━━━━━━━
🌸 봄날 테마 — 감각적 리얼리즘 (동화톤 금지)
━━━━━━━━━━━━━━━━━━━━
- 톤: 따뜻하되 어른의 눈으로. 유아적 감탄이나 과도한 귀여움은 피하라.
- 문체: "~했어요" 가 기본이지만, 연속 3문장 이상 같은 어미 금지. "~었다"·"~였다"·"~한다"·명사 마침으로 리듬을 바꿔라.
- 감각: 햇살·커피 향·손끝의 온도·먼 거리 소음 같은 구체 감각 2~3개를 문단마다 심어라.
- 대사: 다정함은 직접 말하지 말고 침묵·반 문장·사물 건네기로 표현하라.
- 예시 방향:
  ✅ "보리가 컵을 내려놓기 전에 잠깐 손가락 끝으로 테두리를 쓸었다. 그게 무슨 뜻인지 나는 묻지 않았다."
  ❌ "보리가 '오늘도 잘했어요!' 라고 말하며 다정하게 웃었어요."
- 완료한 할 일은 조용한 만족으로, 미완은 여백으로 남기되 "내일 하면 돼요" 같은 직접 위로는 피하라.
- 파트너(${input.partner.name})는 응원 봇이 아니다. 가끔 먼저 피곤해하고, 가끔 다른 곳을 보고, 가끔 사용자가 못 본 것을 본다.

🚫 봄날에서도 절대 금지:
- "우리 오늘 잘했어요" 류 요약 대사
- "다음 주엔 더 많은 이야기를 만들고 싶어요" 류 다짐조 마무리
- 파트너가 모든 장면에 등장하며 긍정적 반응만 하는 구조
- 할 일 목록을 시간 순서대로 기계적으로 배열

이 지시를 바탕으로 위의 주간 기록을 소설로 써라. 요약하지 말고, 한 장면에 머물러라.`;

  return base + springExtension;
}
